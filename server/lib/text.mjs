/**
 * 창 제목·앱 이름 다듬기.
 *
 * 제목은 다른 프로그램이 정한다. 그 안에는 화면을 속이는 글자가 들어올 수 있다 —
 * 방향 뒤집기(U+202E)를 넣으면 `file<RLO>gnp.exe` 가 화면에서 `fileexe.png` 로 보이고,
 * 폭 없는 글자를 끼우면 서로 다른 제목이 똑같아 보인다. 시간을 어디에 썼는지 읽는 도구에서
 * 제목을 잘못 읽게 만드는 것은 그 자체로 기록을 못 믿게 만드는 일이다.
 *
 * 줄바꿈·탭 같은 제어문자도 한 줄 표시와 CSV 를 흐트러뜨리므로 공백으로 바꾼다.
 * 내용 자체는 건드리지 않는다 — 보이지 않는 글자만 걷어 낸다.
 *
 * 앞뒤 공백을 떼는 것도 여기서 한다. `"Adobe Acrobat "` 처럼 뒤에 공백 하나가 붙은
 * 앱 이름은 화면에서 앞의 것과 구별되지 않는데, 집계에서는 다른 앱이 된다 —
 * "많이 쓴 앱" 목록에 같은 이름이 두 줄로 서고, 아무도 이유를 알 수 없다.
 *
 * 추적기와 마이그레이션이 함께 쓰므로 따로 두었다. 둘이 다른 규칙을 쓰면
 * 어제 기록과 오늘 기록이 다른 방식으로 다듬어진다.
 */
const INVISIBLE = new RegExp(
  '[\\u0000-\\u001f\\u007f\\u200b-\\u200f\\u202a-\\u202e\\u2066-\\u2069\\ufeff]',
  'g',
);

export function sanitizeTitle(text) {
  return String(text || '').replace(INVISIBLE, ' ').replace(/\s+/g, ' ').trim();
}
